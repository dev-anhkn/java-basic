package org.example.utils;

/**
 * Đây là class demo javadoc cơ bản
 */
public class NumberUtil {

    /**
     * So sánh hai số và trả về giá trị lớn hơn.
     * Sử dụng toán tử &lt; và &gt; để so sánh.
     */
    public static int max(int a, int b) {
        return (a > b) ? a : b;
    }


}
